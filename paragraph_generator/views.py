def _sse_format(data: str) -> str:
        # Format a chunk for Server-Sent Events
        # Replace any lone newlines to keep SSE integrity
        safe = data.replace('\r', '')
        lines = safe.split('\n')
        return ''.join(f"data: {line}\n" for line in lines) + "\n"


