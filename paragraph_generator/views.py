def stream_generate(request):
        """SSE endpoint that streams generated content progressively.

        Uses the existing generator; if the upstream client returns a full
        response, we chunk it locally and stream to the client so the UI
        receives partial updates quickly. Designed to be run under ASGI.
        """
        topic = (request.GET.get('topic') or '').strip()
        if not topic:
            return JsonResponse({'status': 'error', 'message': 'Topic is required.'}, status=400)

        system = (
            "You are Kitto AI, a professional AI Writing Assistant and Content Generator. "
            "Generate high-quality, structured, and informative content based on the user's prompt. "
            "Do not add unnecessary conversational filler; output the generated content directly."
        )

        def event_stream():
            # Send an initial comment to establish the stream
            yield ': connected\n\n'

            # Send metadata event (default: not fallback)
            import json
            yield 'event: meta\n'
            yield f"data: {json.dumps({'is_fallback': False})}\n\n"

            try:
                api_key = os.environ.get('MAIN_API_KEY')
                if not api_key:
                    # No API key — stream fallback content and mark it in meta
                    fallback = generate_fallback_content(topic)
                    yield 'event: meta\n'
                    yield f"data: {json.dumps({'is_fallback': True, 'reason': 'no_api_key'})}\n\n"
                    import re
                    chunks = re.split(r'(?<=[.!?])\s+', fallback)
                    for part in chunks:
                        if not part:
                            continue
                        yield _sse_format(part)
                        yield '\n'
                    yield 'event: done\n'
                    yield '\n'
                    # Persist fallback
                    try:
                        word_count = len(fallback.split())
                        GeneratedContent.objects.create(
                            prompt=topic,
                            content=fallback,
                            word_count=word_count,
                            topic=topic[:200],
                        )
                    except Exception:
                        logger.exception('Failed to save fallback content')
                    return

                client = genai.Client(api_key=api_key)
                resp = client.models.generate_content(
                    model=getattr(settings, 'GEMINI_MODEL', 'gemini-2.0-flash'), contents=f"{topic}\n{system}"
                )
                content = resp.text or ''

                if not content:
                    # send an error message and close
                    yield _sse_format('No content generated by the API.')
                    yield 'event: done\n'
                    yield '\n'
                    return

                # Chunk the response for progressive rendering (by sentences)
                import re
                chunks = re.split(r'(?<=[.!?])\s+', content)
                for part in chunks:
                    if not part:
                        continue
                    yield _sse_format(part)
                    yield '\n'

                # final done event
                yield 'event: done\n'
                yield '\n'

                # Persist to DB
                try:
                    word_count = len(content.split())
                    GeneratedContent.objects.create(
                        prompt=topic,
                        content=content,
                        word_count=word_count,
                        topic=topic[:200],
                    )
                except Exception:
                    logger.exception('Failed to save generated content')

            except Exception as e:
                logger.exception('Streaming generation failed: %s', e)
                yield _sse_format('Error: failed to generate content')
                yield '\n'

        return StreamingHttpResponse(event_stream(), content_type='text/event-stream')


